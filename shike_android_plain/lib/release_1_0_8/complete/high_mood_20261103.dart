Future<String> highMoodPhrase(CompleteController controller) async {
  const key = 'refined.recent.high';
  final recent = controller.prefs?.getStringList(key) ?? <String>[];
  final available = highMoodPhrases.where((s) => !recent.contains(s)).toList();
  final selected = available[Random().nextInt(available.length)];
  await controller.prefs?.setStringList(key, [selected, ...recent].take(5).toList());
  return selected;
}
